  await overlap.getByRole("button",{name:"Confirm move",exact:true}).click();await expect.poll(()=>db.itineraryItem.count({where:{tripId:DEMO_TRIP_ID,day:{date:new Date("2030-04-01T00:00:00Z")}}})).toBe(1);
