  await expect(preview).toContainText("This item is marked Fixed.");await expect(order).toHaveText(["Free time","Hotel / Rest",title]);
  await preview.getByRole("button",{name:"Cancel",exact:true}).click();await expect(preview).toHaveCount(0);
