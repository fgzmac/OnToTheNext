  const persistedTransport=await db.itineraryItem.findFirstOrThrow({where:{tripId:DEMO_TRIP_ID,type:"TRANSPORTATION"}});
  expect(persistedTransport).toMatchObject({transportationMode:"TRAIN",notes:"Synthetic transfer plan",flexibility:"FIXED",originSegmentId:"cmg00000000000000000000011",destinationSegmentId:"cmg00000000000000000000012"});
  await closeDetails(page);
  const title="Train · Tokyo → Kyoto",order=page.locator(".timeline-item h3");
  await expect(order).toHaveText(["Free time","Hotel / Rest",title]);
  await expect(page.getByRole("region",{name:"Time warnings for 2030-04-01"})).toContainText("Free time (09:00–10:00) overlaps Train · Tokyo → Kyoto (09:30–10:00)");
  await page.reload();await expect(order).toHaveText(["Free time","Hotel / Rest",title]);
  await openItem(page,"Free time");await expect(drawer.getByRole("button",{name:"Move Free time earlier",exact:true})).toBeDisabled();
  await drawer.getByRole("button",{name:"Move Free time later",exact:true}).focus();await page.keyboard.press("Enter");
  await expect(order).toHaveText(["Hotel / Rest","Free time",title]);await page.reload();
  await expect(order).toHaveText(["Hotel / Rest","Free time",title]);
  await drawer.getByRole("button",{name:"Move Free time earlier",exact:true}).focus();await page.keyboard.press("Enter");
  await expect(order).toHaveText(["Free time","Hotel / Rest",title]);await closeDetails(page);await page.reload();
